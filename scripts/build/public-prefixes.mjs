#!/usr/bin/env node
/**
 * Emit the publishable R2 prefixes as a module the Pages Functions can import.
 *
 * WHY NOT READ THE ALLOWLIST AT RUNTIME
 *
 * data/database/r2-publication-allowlist.json is operational config, not site content, and
 * .cfignore says so: "publishing it would hand out a map of the bucket's prefix layout for
 * no benefit to any reader". It also carries rationale, evidence and rights notes that are
 * internal working material. A Function that fetched it would either need it deployed --
 * defeating that -- or would fail closed at runtime, which for a public index means an
 * outage rather than a safe default.
 *
 * So the PREFIX STRINGS ONLY are extracted here at build time and compiled in. The
 * rationale, evidence and rights text stays out of the deployed bundle.
 *
 * WHY THIS IS THE SAFETY BOUNDARY
 *
 * functions/_api/data-index lists the public bucket. Without a fixed list it would expose
 * whatever happens to be in the bucket, and six prefixes are currently in there that never
 * passed the allowlist -- data/deprivation/, data/nisra-files/, data/nisra-portal/,
 * data/pointclouds/, data/polling/, data/thumbnails/. Generating from the allowlist means
 * anything unreviewed is invisible to the public index by construction, not by remembering.
 *
 * Runs inside `npm run build`. --check fails instead of writing, which is what the gate uses.
 *
 *   node scripts/build/public-prefixes.mjs
 *   node scripts/build/public-prefixes.mjs --check
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const ALLOWLIST = 'data/database/r2-publication-allowlist.json';
const OUT = 'functions/_api/_public-prefixes.js';
const CHECK = process.argv.includes('--check');

if (!existsSync(ALLOWLIST)) {
  console.error(`FAIL: ${ALLOWLIST} is missing. It is the source of truth for what may be`);
  console.error('  published; without it the public index cannot be generated safely.');
  process.exit(1);
}

const allowlist = JSON.parse(readFileSync(ALLOWLIST, 'utf8'));
const prefixes = (allowlist.prefixes || [])
  .map((entry) => entry.prefix)
  .filter(Boolean)
  .sort();

if (!prefixes.length) {
  console.error('FAIL: the allowlist contains no prefixes. Refusing to emit an empty list,');
  console.error('  which would silently disable the public index rather than fail loudly.');
  process.exit(1);
}

const body = `// GENERATED by scripts/build/public-prefixes.mjs -- do not edit.
//
// The R2 key prefixes approved for publication, taken from
// data/database/r2-publication-allowlist.json. Only the prefix strings are compiled in;
// the rationale, evidence and rights notes stay out of the deployed bundle.
//
// functions/_api/data-index serves ONLY what is listed here. A prefix that reaches the
// bucket without passing the allowlist is invisible to the public index by construction.

export const PUBLIC_PREFIXES = ${JSON.stringify(prefixes, null, 2)};

/** True when a key or prefix sits inside an approved prefix. */
export function isPublicPrefix(key) {
  const value = String(key || '').replace(/^\\/+/, '');
  return PUBLIC_PREFIXES.some((prefix) => value.startsWith(prefix));
}

/** True when a listing prefix is approved, or is a parent an approved prefix sits under. */
export function isListablePrefix(prefix) {
  const value = String(prefix || '').replace(/^\\/+/, '');
  if (!value) return true;
  return PUBLIC_PREFIXES.some((allowed) => value.startsWith(allowed) || allowed.startsWith(value));
}
`;

if (CHECK) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current !== body) {
    console.error(`FAIL: ${OUT} is stale.`);
    console.error('  It is generated from the R2 publication allowlist and compiled into the');
    console.error('  public index. Stale means the index can serve a prefix the allowlist has');
    console.error('  retired, or hide one it has approved.');
    console.error('  Fix: node scripts/build/public-prefixes.mjs');
    process.exit(1);
  }
  console.log(`PASS: ${OUT} matches the allowlist (${prefixes.length} prefixes).`);
  process.exit(0);
}

writeFileSync(OUT, body);
console.log(`Wrote ${prefixes.length} public prefix(es) into ${OUT}:`);
for (const prefix of prefixes) console.log(`  ${prefix}`);
