#!/usr/bin/env node
/**
 * The compact layer index must contain exactly the layers the full metadata does.
 *
 * WHY. On 2026-08-04 two new layers and eight alias parts were added to
 * render/metadata/maps-test.json, but render/metadata/maps-test-index.json -- which the app
 * actually reads -- was never regenerated. npm run check passed. The site shipped with
 * eds-roi-1931 absent from the catalogue entirely and eds-roi-1936 unable to resolve its
 * parts, which the collaborator reported as "loading 1936 loads the 1941 map and 1931
 * isn't present at all".
 *
 * Nothing in the gate compared the two files, so a stale index was invisible. The index
 * is generated by scripts/build/build-test2-metadata-shards.mjs; this only checks that someone
 * remembered to run it.
 */
import { existsSync, readFileSync } from 'node:fs';

const FULL = 'render/metadata/maps-test.json';
const INDEX = 'render/metadata/maps-test-index.json';

for (const path of [FULL, INDEX]) {
  if (!existsSync(path)) {
    console.error(`validate-test-index-parity: missing ${path}`);
    process.exit(1);
  }
}

/** @typedef {{ layers?: { id?: string }[], entries?: { id?: string }[] }} LayerDoc */
/**
 * @param {string} path
 * @param {(doc: LayerDoc) => { id?: string }[] | undefined} pick
 */
const ids = (path, pick) => new Set((pick(JSON.parse(readFileSync(path, 'utf8'))) || []).map((l) => l.id).filter(Boolean));
const full = ids(FULL, (d) => d.layers);
const index = ids(INDEX, (d) => d.layers || d.entries);

const missing = [...full].filter((id) => !index.has(id)).sort();
const extra = [...index].filter((id) => !full.has(id)).sort();

console.log('Test layer index parity');
console.log(`- ${FULL}: ${full.size} layers`);
console.log(`- ${INDEX}: ${index.size} layers`);

if (!missing.length && !extra.length) {
  console.log('PASS: the compact index matches the full metadata.');
  process.exit(0);
}

if (missing.length) {
  console.error(`\nFAIL: ${missing.length} layer(s) in the full metadata are absent from the index.`);
  console.error('These layers cannot be found by the app at all. Run: node scripts/build/build-test2-metadata-shards.mjs');
  for (const id of missing.slice(0, 20)) console.error(`- ${id}`);
  if (missing.length > 20) console.error(`  ... and ${missing.length - 20} more`);
}
if (extra.length) {
  console.error(`\nFAIL: ${extra.length} layer(s) in the index no longer exist in the full metadata.`);
  for (const id of extra.slice(0, 20)) console.error(`- ${id}`);
}
process.exit(1);
