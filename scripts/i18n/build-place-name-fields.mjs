#!/usr/bin/env node
/**
 * Which tile property holds the Irish name of each map layer's features.
 *
 * WHY
 *
 * Many layers already carry an official Irish name beside the English one, because their source
 * publishes both: Tailte Éireann (ex-OSi) boundary data has ENGLISH/GAEILGE and
 * ENG_NAME_VALUE/GLE_NAME_VALUE (names from the Placenames Database of Ireland, Logainm, both
 * CC BY 4.0); the CSO 2022 electoral divisions have ED_ENGLISH/ED_GAEILGE; OpenStreetMap
 * layers have name:ga (ODbL). When the interface is in Irish the map labels and the feature
 * details use that property (src/map/renderer/labels.js), falling back to the English label for any
 * feature whose Irish name is blank. No place name is fetched or invented here: this only pairs
 * each layer's label property with the Irish property its own data already has.
 *
 * Pairs are by rule, not by name pattern alone: a property called "GA" in a Tellus geochemistry
 * layer is gallium, and "CONTAE" beside a building's NAME is the building's county.
 *
 *   node scripts/i18n/build-place-name-fields.mjs          write assets/i18n/place-name-fields.json
 *                                                          and data/i18n/review/place-name-fields.tsv
 *   node scripts/i18n/build-place-name-fields.mjs --check  fail if either is out of date
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const CHECK = process.argv.includes('--check');
const INDEX = 'render/metadata/maps-test-index.json';
const OUT = 'assets/i18n/place-name-fields.json';
const REVIEW = 'data/i18n/review/place-name-fields.tsv';

/** label property -> Irish properties to try, in order. */
const PAIRS = {
  ENGLISH: ['GAEILGE'],
  ENG_NAME_VALUE: ['GLE_NAME_VALUE'],
  ED_ENGLISH: ['ED_GAEILGE'],
  LE_ENGLISH: ['LE_GAEILGE'],
  COUNTY: ['GAEILGE', 'CONTAE'],
  name_en: ['name_ga'],
  name: ['name:ga'],
  Name: ['IrishName', 'Name_GA'],
  NAME_TAG: ['NAME_GA'],
  MAX_CON_NA: ['MAX_CON_NA_GA'],
  CON_SEAT_: ['CON_SEAT_GA'],
  park_name: ['irish_name'],
  SUB_DIST: ['SUB_IRISH'],
  English_Na: ['Irish_Name'],
  Townland: ['Townland_Irish']
};

/** Where the Irish names in each kind of property come from, for the attribution column. */
function sourceOf(field, layer) {
  const providers = (Array.isArray(layer.provider) ? layer.provider : [layer.provider]).filter(Boolean).join(', ');
  if (/^(GAEILGE|GLE_NAME_VALUE|CONTAE|ED_GAEILGE|LE_GAEILGE)$/.test(field)) return `${providers || 'Tailte Éireann / CSO'}; the layer's own Irish-name attribute (Tailte Éireann / CSO boundary data, Irish forms from Logainm, CC BY 4.0)`;
  if (/^(name:ga|name_ga)$/.test(field)) return `${providers || 'OpenStreetMap'} (name:ga; ODbL)`;
  return providers || 'layer source';
}

function kindOf(layer) {
  const text = `${layer.id} ${layer.category || ''} ${layer.name || ''}`.toLowerCase();
  if (/townland/.test(text)) return 'townlands';
  if (/barony|baronies/.test(text)) return 'baronies';
  if (/civil[- ]parish/.test(text)) return 'civil parishes';
  if (/count(y|ies)/.test(text) && !/electoral|council/.test(text)) return 'counties';
  if (/\bdail|constituenc|mep|european/.test(text)) return 'constituencies';
  if (/electoral[- ]division|\beds?-|\bded/.test(text)) return 'electoral divisions (DEDs/EDs)';
  if (/local[- ]electoral|\blea\b|lea-/.test(text)) return 'local electoral areas';
  return 'other';
}

function build() {
  const index = JSON.parse(readFileSync(INDEX, 'utf8'));
  const layers = {};
  const rows = [['layer_id', 'name', 'kind', 'label_property', 'irish_property', 'source_and_licence']];
  const unpaired = [];
  const byKind = {};
  for (const layer of index.layers || []) {
    const props = new Set([...(layer.categoricalProperties || []), ...(layer.popupProperties || [])]);
    const candidates = PAIRS[layer.labelProperty] || [];
    const field = candidates.find((c) => props.has(c));
    if (!field) {
      const irishLooking = [...props].filter((p) => /gaeilge|_ga$|:ga$|irish/i.test(p) && !/grid|_x$|_y$/i.test(p));
      if (irishLooking.length) unpaired.push([layer.id, layer.labelProperty || '', irishLooking.join(',')]);
      continue;
    }
    layers[layer.id] = field;
    // The map pane looks layers up by their catalogue map id too (maps.json "counties-ireland").
    if (layer.sourceMapId && !(layer.sourceMapId in layers)) layers[layer.sourceMapId] = field;
    const kind = kindOf(layer);
    byKind[kind] = (byKind[kind] || 0) + 1;
    rows.push([layer.id, layer.name || '', kind, layer.labelProperty, field, sourceOf(field, layer)]);
  }
  const json = {
    _status: 'generated',
    _note: 'Layer id -> tile property holding the Irish name of its features. Generated by scripts/i18n/build-place-name-fields.mjs from render/metadata/maps-test-index.json. Only properties the layer data already carries; nothing is fetched.',
    attribution: 'Irish-language placename data by Logainm © Government of Ireland and licensed under CC BY 4.0 (via Tailte Éireann / CSO boundary data); OpenStreetMap name:ga © OpenStreetMap contributors, ODbL.',
    summary: { layers: rows.length - 1, byKind },
    hints: ['GLE_NAME_VALUE', 'ED_GAEILGE', 'LE_GAEILGE', 'name_ga'],
    layers: Object.fromEntries(Object.entries(layers).sort(([a], [b]) => a.localeCompare(b)))
  };
  const tsv = rows.map((r) => r.join('\t')).join('\n') + '\n'
    + '\n# Layers with an Irish-looking property that is NOT paired (label is an id, or the property is something else):\n'
    + unpaired.map((r) => `# ${r.join('\t')}`).join('\n') + '\n';
  return { json: `${JSON.stringify(json, null, 1)}\n`, tsv, summary: json.summary };
}

const { json, tsv, summary } = build();
const stale = [];
for (const [file, content] of [[OUT, json], [REVIEW, tsv]]) {
  const current = existsSync(file) ? readFileSync(file, 'utf8').replace(/\r\n/g, '\n') : null;
  if (current === content) continue;
  if (CHECK) stale.push(file);
  else {
    mkdirSync(file.replace(/\/[^/]+$/, ''), { recursive: true });
    writeFileSync(file, content);
  }
}
if (stale.length) {
  console.error(`FAIL: out of date (run node scripts/i18n/build-place-name-fields.mjs): ${stale.join(', ')}`);
  process.exit(1);
}
console.log(`Irish place-name properties: ${summary.layers} layers`, summary.byKind);
