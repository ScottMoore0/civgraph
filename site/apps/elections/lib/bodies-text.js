/**
 * A pattern with its numbers and names filled in ({n}, {k}, {m}, {total}, {year}, {name}).
 * @param {string} pattern @param {Record<string, string | number>} values
 */
export function fill(pattern, values) {
  return pattern.replace(/\{(\w+)\}/g, (all, k) => (k in values ? String(values[k]) : all));
}
